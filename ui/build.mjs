// Turns tokens.json (DTCG 2025.10) into CSS variables and prepends them to components.css.
// Dependency-free on purpose: the extension has no bundler, and this is the only build grod UI needs.
// Writes ui/grod.css and the extension copy, the same way `grod sync` writes the rules copies.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const here = new URL('.', import.meta.url).pathname;
const tokens = JSON.parse(readFileSync(join(here, 'tokens.json'), 'utf8'));
const components = readFileSync(join(here, 'components.css'), 'utf8');
const outputs = [join(here, 'grod.css'), join(here, '../extension/ui/grod.css')];

// Mode groups are dropped from variable names so light and dark define the same --g-* names.
const MODES = ['light', 'dark'];
const varName = (path) => `--g-${path.filter((p) => !MODES.includes(p)).join('-')}`;

function collect(group, path = [], type) {
  const out = [];
  for (const [key, node] of Object.entries(group)) {
    if (key.startsWith('$') || typeof node !== 'object') continue;
    const nodeType = node.$type ?? type;
    if ('$value' in node) out.push({ path: [...path, key], type: nodeType, value: node.$value });
    else out.push(...collect(node, [...path, key], nodeType));
  }
  return out;
}

function css({ type, value }) {
  if (typeof value === 'string' && value.startsWith('{')) return `var(${varName(value.slice(1, -1).split('.'))})`;
  switch (type) {
    case 'color': {
      if (value.colorSpace !== 'oklch') throw new Error(`Unsupported color space ${value.colorSpace}`);
      const [l, c, h] = value.components;
      return `oklch(${l.toFixed(3)} ${c.toFixed(3)} ${h})`;
    }
    case 'dimension':
    case 'duration':
      return `${value.value}${value.unit}`;
    case 'fontFamily':
      return value.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(', ');
    case 'cubicBezier':
      return `cubic-bezier(${value.join(', ')})`;
    case 'fontWeight':
    case 'number':
      return String(value);
    default:
      throw new Error(`Unsupported token type ${type}`);
  }
}

const all = collect(tokens);
const block = (list) => list.map((t) => `  ${varName(t.path)}: ${css(t)};`).join('\n');
const mode = (m) => all.filter((t) => t.path[0] === 'color' && t.path[1] === m);
const shared = all.filter((t) => !(t.path[0] === 'color' && MODES.includes(t.path[1])));
const durations = all.filter((t) => t.type === 'duration');

// data-g-theme forces a mode on any subtree (the showcase shows both side by side);
// :not([data-g-theme="light"]) keeps a forced-light root light when the OS is dark.
const variables = `/* Generated by ui/build.mjs from ui/tokens.json and ui/components.css. Edit those, then run node ui/build.mjs. */

:root {
${block(shared)}
}

:root,
[data-g-theme="light"] {
  color-scheme: light;
${block(mode('light'))}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-g-theme="light"]) {
    color-scheme: dark;
${block(mode('dark')).replace(/^/gm, '  ')}
  }
}

[data-g-theme="dark"] {
  color-scheme: dark;
${block(mode('dark'))}
}

@media (prefers-reduced-motion: reduce) {
  :root {
${durations.map((t) => `    ${varName(t.path)}: 0ms;`).join('\n')}
  }
}
`;

for (const file of outputs) {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, `${variables}\n${components}`);
  console.log(`wrote ${file}`);
}
