// Turns tokens.json (DTCG 2025.10) into CSS variables and prepends them to components.css, and
// writes the colors as Android resources (light in values/, dark in values-night/) and as SwiftUI colors for the macOS app.
// Dependency-free on purpose: the extension has no bundler, and this is the only build grod UI needs.
// Writes ui/grod.css, the extension copy and the landing page copy, the same way `grod sync` writes the rules copies.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const here = new URL('.', import.meta.url).pathname;
const tokens = JSON.parse(readFileSync(join(here, 'tokens.json'), 'utf8'));
const components = readFileSync(join(here, 'components.css'), 'utf8');
const outputs = [join(here, 'grod.css'), join(here, '../extension/ui/grod.css'), join(here, '../site/grod.css')];

// Mode groups are dropped from variable names so light and dark define the same --g-* names.
const MODES = ['light', 'dark'];
const varName = (path) => `--g-${path.filter((p) => !MODES.includes(p)).join('-')}`;

function collect(group, path = [], type) {
  const out = [];
  for (const [key, node] of Object.entries(group)) {
    if (key.startsWith('$') || typeof node !== 'object') continue;
    const nodeType = node.$type ?? type;
    if ('$value' in node) out.push({ path: [...path, key], type: nodeType, value: node.$value });
    else out.push(...collect(node, [...path, key], nodeType));
  }
  return out;
}

function css({ type, value }) {
  if (typeof value === 'string' && value.startsWith('{')) return `var(${varName(value.slice(1, -1).split('.'))})`;
  switch (type) {
    case 'color': {
      if (value.colorSpace !== 'oklch') throw new Error(`Unsupported color space ${value.colorSpace}`);
      const [l, c, h] = value.components;
      return `oklch(${l.toFixed(3)} ${c.toFixed(3)} ${h})`;
    }
    case 'dimension':
    case 'duration':
      return `${value.value}${value.unit}`;
    case 'fontFamily':
      return value.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(', ');
    case 'cubicBezier':
      return `cubic-bezier(${value.join(', ')})`;
    case 'fontWeight':
    case 'number':
      return String(value);
    default:
      throw new Error(`Unsupported token type ${type}`);
  }
}

const all = collect(tokens);
const block = (list) => list.map((t) => `  ${varName(t.path)}: ${css(t)};`).join('\n');
const mode = (m) => all.filter((t) => t.path[0] === 'color' && t.path[1] === m);
const shared = all.filter((t) => !(t.path[0] === 'color' && MODES.includes(t.path[1])));
const durations = all.filter((t) => t.type === 'duration');

// data-g-theme forces a mode on any subtree (the showcase shows both side by side);
// :not([data-g-theme="light"]) keeps a forced-light root light when the OS is dark.
const variables = `/* Generated by ui/build.mjs from ui/tokens.json and ui/components.css. Edit those, then run node ui/build.mjs. */

:root {
${block(shared)}
}

:root,
[data-g-theme="light"] {
  color-scheme: light;
${block(mode('light'))}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-g-theme="light"]) {
    color-scheme: dark;
${block(mode('dark')).replace(/^/gm, '  ')}
  }
}

[data-g-theme="dark"] {
  color-scheme: dark;
${block(mode('dark'))}
}

@media (prefers-reduced-motion: reduce) {
  :root {
${durations.map((t) => `    ${varName(t.path)}: 0ms;`).join('\n')}
  }
}
`;

for (const file of outputs) {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, `${variables}\n${components}`);
  console.log(`wrote ${file}`);
}

// Android has no OKLCH, so colors go out as sRGB hex: OKLCH -> OKLab -> linear sRGB (Björn Ottosson's
// matrices) -> gamma. A color outside sRGB loses chroma (hue and lightness kept) until it fits.
function oklchToLinear([l, c, h]) {
  const a = c * Math.cos((h * Math.PI) / 180);
  const b = c * Math.sin((h * Math.PI) / 180);
  const L = (l + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const M = (l - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const S = (l - 0.0894841775 * a - 1.291485548 * b) ** 3;
  return [
    4.0767416621 * L - 3.3077115913 * M + 0.2309699292 * S,
    -1.2684380046 * L + 2.6097574011 * M - 0.3413193965 * S,
    -0.0041960863 * L - 0.7034186147 * M + 1.707614701 * S,
  ];
}

const inGamut = (rgb) => rgb.every((v) => v >= -1e-4 && v <= 1 + 1e-4);

function oklchToHex([l, c, h]) {
  let rgb = oklchToLinear([l, c, h]);
  if (!inGamut(rgb)) {
    let lo = 0;
    let hi = c;
    for (let i = 0; i < 30; i++) {
      const mid = (lo + hi) / 2;
      if (inGamut(oklchToLinear([l, mid, h]))) lo = mid;
      else hi = mid;
    }
    rgb = oklchToLinear([l, lo, h]);
  }
  const gamma = (v) => {
    const x = Math.min(1, Math.max(0, v));
    return x <= 0.0031308 ? 12.92 * x : 1.055 * x ** (1 / 2.4) - 0.055;
  };
  return '#' + rgb.map((v) => Math.round(gamma(v) * 255).toString(16).padStart(2, '0')).join('');
}

const byPath = new Map(all.map((t) => [t.path.join('.'), t]));
const resolve = (t) => (typeof t.value === 'string' ? resolve(byPath.get(t.value.slice(1, -1))) : t.value);

const androidRes = join(here, '../android/app/src/main/res');
for (const [m, dir] of [['light', 'values'], ['dark', 'values-night']]) {
  const colors = mode(m)
    .map((t) => `    <color name="grod_${t.path.at(-1).replaceAll('-', '_')}">${oklchToHex(resolve(t).components)}</color>`)
    .join('\n');
  const file = join(androidRes, dir, 'grod_colors.xml');
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(
    file,
    `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by ui/build.mjs from ui/tokens.json (${m}). Edit the tokens, then run node ui/build.mjs. -->\n<!-- The whole palette ships, used or not, so lint's unused-resource check is off here. -->\n<resources xmlns:tools="http://schemas.android.com/tools" tools:ignore="UnusedResources">\n${colors}\n</resources>\n`,
  );
  console.log(`wrote ${file}`);
}

// macOS: one SwiftUI Color per token that follows the window's appearance, from the same sRGB hex.
const swiftName = (name) => name.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const swiftHex = (t, m) => '0x' + oklchToHex(resolve(byPath.get(`color.${m}.${t.path.at(-1)}`)).components).slice(1);
const swiftColors = mode('light')
  .map((t) => `    static let ${swiftName(t.path.at(-1))} = dynamic(light: ${swiftHex(t, 'light')}, dark: ${swiftHex(t, 'dark')})`)
  .join('\n');
const swiftFile = join(here, '../macos/Sources/GrodBar/GrodColors.swift');
writeFileSync(
  swiftFile,
  `// Generated by ui/build.mjs from ui/tokens.json. Edit the tokens, then run node ui/build.mjs.
import AppKit
import SwiftUI

enum GrodColor {
${swiftColors}

    private static func dynamic(light: Int, dark: Int) -> Color {
        Color(nsColor: NSColor(name: nil) { appearance in
            let hex = appearance.bestMatch(from: [.aqua, .darkAqua]) == .darkAqua ? dark : light
            return NSColor(srgbRed: CGFloat((hex >> 16) & 0xff) / 255, green: CGFloat((hex >> 8) & 0xff) / 255,
                           blue: CGFloat(hex & 0xff) / 255, alpha: 1)
        })
    }
}
`,
);
console.log(`wrote ${swiftFile}`);

// The component showcase is published with the landing page at grod.efekurucay.com/ui/.
const showcase = join(here, '../site/ui/index.html');
mkdirSync(dirname(showcase), { recursive: true });
writeFileSync(showcase, readFileSync(join(here, 'index.html'), 'utf8').replace('href="grod.css"', 'href="../grod.css"'));
console.log(`wrote ${showcase}`);
